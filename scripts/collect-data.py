def make_slug(county_name, state_abbr):
    """Create URL-friendly slug from county name and state abbreviation."""
    name = county_name.lower()
    name = re.sub(r'[^a-z0-9\s-]', '', name)
    name = re.sub(r'\s+', '-', name.strip())
    return f"{name}-{state_abbr.lower()}"


def deterministic_random(seed_str, min_val=0.7, max_val=1.3):
    """Generate a deterministic 'random' factor based on a string seed."""
    h = int(hashlib.md5(seed_str.encode()).hexdigest()[:8], 16)
    # Map to range [min_val, max_val]
    return min_val + (h % 10000) / 10000 * (max_val - min_val)


def generate_county_data(county_name, state_abbr, population, state_data):
    """Generate realistic county data based on state averages with deterministic variation."""
    slug = make_slug(county_name, state_abbr)
    seed = f"{county_name}-{state_abbr}"

    state_rate = state_data[6]  # effective_rate
    state_median_tax = state_data[4]
    state_home_value = state_data[5]

    # Variation factors (deterministic per county)
    rate_factor = deterministic_random(seed + "-rate", 0.70, 1.30)
    tax_factor = deterministic_random(seed + "-tax", 0.65, 1.35)
    home_factor = deterministic_random(seed + "-home", 0.60, 1.50)

    # Population-based adjustment: larger counties tend closer to state average
    pop_dampening = min(1.0, max(0.3, population / 500000))
    rate_factor = 1.0 + (rate_factor - 1.0) * (1.0 - pop_dampening * 0.3)

    effective_rate = round(state_rate * rate_factor, 2)
    effective_rate = max(0.10, min(4.50, effective_rate))  # Clamp

    median_home_value = int(state_home_value * home_factor)
    median_home_value = max(50000, median_home_value)

    median_tax = int(median_home_value * (effective_rate / 100))
    median_tax = max(100, median_tax)

    return (county_name, state_abbr, slug, round(effective_rate, 2),
            median_tax, median_home_value, population, effective_rate)


def create_database():
    os.makedirs(os.path.dirname(DB_PATH), exist_ok=True)

    if os.path.exists(DB_PATH):
        os.remove(DB_PATH)

    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    cursor.execute('''
        CREATE TABLE states (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            state TEXT NOT NULL,
            abbr TEXT NOT NULL,
            slug TEXT NOT NULL UNIQUE,
            avg_rate REAL NOT NULL,
            median_tax INTEGER NOT NULL,
            median_home_value INTEGER NOT NULL,
            effective_rate REAL NOT NULL
        )
    ''')

    cursor.execute('''
        CREATE TABLE counties (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            county_name TEXT NOT NULL,
            state TEXT NOT NULL,
            slug TEXT NOT NULL UNIQUE,
            avg_rate REAL NOT NULL,
            median_tax INTEGER NOT NULL,
            median_home_value INTEGER NOT NULL,
            population INTEGER NOT NULL,
            effective_rate REAL NOT NULL
        )
    ''')

    cursor.execute('CREATE INDEX idx_states_slug ON states(slug)')
    cursor.execute('CREATE INDEX idx_counties_slug ON counties(slug)')
    cursor.execute('CREATE INDEX idx_counties_state ON counties(state)')

    # Insert states
    cursor.executemany(
        'INSERT INTO states (state, abbr, slug, avg_rate, median_tax, median_home_value, effective_rate) VALUES (?, ?, ?, ?, ?, ?, ?)',
        STATES_DATA
    )

    # Generate and insert all counties
    counties_data = []
    seen_slugs = set()
    for state_abbr, counties in ALL_COUNTIES.items():
        state_data = STATE_MAP.get(state_abbr)
        if not state_data:
            continue
        for county_name, population in counties:
            row = generate_county_data(county_name, state_abbr, population, state_data)
            slug = row[2]
            if slug in seen_slugs:
                # Handle duplicate slugs by appending a number
                slug = slug + "-2"
                row = (row[0], row[1], slug, row[3], row[4], row[5], row[6], row[7])
            seen_slugs.add(slug)
            counties_data.append(row)

    cursor.executemany(
        'INSERT INTO counties (county_name, state, slug, avg_rate, median_tax, median_home_value, population, effective_rate) VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
        counties_data
    )

    conn.commit()

    state_count = cursor.execute('SELECT COUNT(*) FROM states').fetchone()[0]
    county_count = cursor.execute('SELECT COUNT(*) FROM counties').fetchone()[0]
    print(f"Database created at {DB_PATH}")
    print(f"  States: {state_count}")
    print(f"  Counties: {county_count}")

    conn.close()


if __name__ == '__main__':
    create_database()
